#!/usr/bin/env python3
"""Generate .github/workflows/ci.yaml from templates/.github/workflows/ci.yaml.

This repo's CI is the template's CI run against templates/, so the template
workflow is tested on every push without keeping two copies by hand.

    scripts/sync-ci.py          # rewrite .github/workflows/ci.yaml
    scripts/sync-ci.py --check  # exit 1 if it is out of date (pre-commit)
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "templates/.github/workflows/ci.yaml"
TARGET = ROOT / ".github/workflows/ci.yaml"

HEADER = """\
# GENERATED by scripts/sync-ci.py from templates/.github/workflows/ci.yaml.
# Edit the template, then run scripts/sync-ci.py. Builds templates/.

"""


def generate() -> str:
    text = SOURCE.read_text()
    # Run every shell step inside templates/.
    text = text.replace(
        "\njobs:\n",
        "\ndefaults:\n  run:\n    working-directory: templates\n\njobs:\n",
        1,
    )
    # hashFiles() and cache globs are relative to the repo root, not the
    # working directory.
    text = re.sub(
        r"hashFiles\(([^)]*)\)",
        lambda m: (
            "hashFiles(" + re.sub(r"'([^']+)'", r"'templates/\1'", m.group(1)) + ")"
        ),
        text,
    )
    text = text.replace(
        "cache-dependency-glob: tests/", "cache-dependency-glob: templates/tests/"
    )
    return HEADER + text


def main() -> int:
    expected = generate()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text() != expected:
            print(f"{TARGET.relative_to(ROOT)} is stale; run scripts/sync-ci.py")
            return 1
        return 0
    TARGET.write_text(expected)
    return 0


if __name__ == "__main__":
    sys.exit(main())
